const update = process.argv.includes('--update');
const existing = new Map(listTemplates().map((t) => [t.title, t.id]));
let added = 0;
let updated = 0;
db.transaction(() => {
  for (const t of TEMPLATES) {
    if (!existing.has(t.title)) {
      createTemplate(t.title, t.body);
      added++;
    } else if (update) {
      updateTemplate(existing.get(t.title), t.title, t.body);
      updated++;
    }
  }
})();
console.log(`Added ${added}, updated ${updated}, skipped ${TEMPLATES.length - added - updated}.`);
